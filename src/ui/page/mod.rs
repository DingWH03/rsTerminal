//! 页面模块 — 应用的所有全屏页面。
//!
//! 每个子模块对应一个独立的功能页面：
//! - `home`：首页，显示已保存的连接列表和快捷操作。
//! - `terminal`：终端仿真页面，包含终端网格渲染、输入处理、鼠标事件、选择和高亮。
//! - `settings`：设置页面，管理应用配置、主题、快捷键等。
//! - `file_manager`：文件管理器页面，支持本地和 SFTP 远程文件浏览与传输。

/// 首页模块 — 连接管理、最近连接、收藏夹。
pub mod home;
/// 终端仿真页面模块 — 网格渲染、键盘输入、鼠标交互、文本选择。
pub mod terminal;
/// 设置页面模块 — 应用配置、主题、键盘、行为等。
pub mod settings;
/// 文件管理器模块 — 本地和远程 SFTP 文件浏览、复制、移动、传输。
pub mod file_manager;
